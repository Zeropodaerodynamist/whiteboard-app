'use strict';
// Copies the browser builds of third-party libraries into vendor/ so the app
// loads them with plain <script> tags (web and Electron alike, no bundler).
// Runs automatically after `npm install`.

const fs = require('fs');
const path = require('path');

const ROOT = path.join(__dirname, '..');
const NM = path.join(ROOT, 'node_modules');
const OUT = path.join(ROOT, 'vendor');

const FILES = {
  'codemirror/lib/codemirror.js': 'codemirror/codemirror.js',
  'codemirror/lib/codemirror.css': 'codemirror/codemirror.css',
  'codemirror/mode/markdown/markdown.js': 'codemirror/markdown.js',
  'codemirror/mode/xml/xml.js': 'codemirror/xml.js',
  'codemirror/addon/edit/continuelist.js': 'codemirror/continuelist.js',
  'codemirror/addon/display/placeholder.js': 'codemirror/placeholder.js',
  'codemirror/addon/selection/active-line.js': 'codemirror/active-line.js',
  'dompurify/dist/purify.min.js': 'purify.min.js',
};

// marked moved its browser build between major versions.
const MARKED = ['marked/lib/marked.umd.js', 'marked/marked.min.js'].find(p => fs.existsSync(path.join(NM, p)));
if (MARKED) FILES[MARKED] = 'marked.js';

let missing = 0;
for (const [src, dest] of Object.entries(FILES)) {
  const from = path.join(NM, src);
  if (!fs.existsSync(from)) { console.warn('vendor: missing', src); missing++; continue; }
  const to = path.join(OUT, dest);
  fs.mkdirSync(path.dirname(to), { recursive: true });
  fs.copyFileSync(from, to);
}
if (!MARKED) { console.warn('vendor: marked browser build not found'); missing++; }

// Emoji picker data: names and groups from unicode-emoji-json, search keywords from emojilib,
// trimmed to [emoji, name, keywords, skin-tone flag] per emoji. Emoji newer than 15.1 are
// left out: Windows' Segoe UI Emoji can't draw them yet.
try {
  const groups = require(path.join(NM, 'unicode-emoji-json', 'data-by-group.json'));
  const keywords = require(path.join(NM, 'emojilib', 'dist', 'emoji-en-US.json'));
  const MAX_VERSION = 15.1;
  const data = groups.map(g => [g.name, g.emojis
    .filter(e => parseFloat(e.emoji_version) <= MAX_VERSION)
    .map(e => [e.emoji, e.name, (keywords[e.emoji] || []).filter(k => !e.name.includes(k.replace(/_/g, ' '))).join(' ').replace(/_/g, ' '), e.skin_tone_support ? 1 : 0])]);
  fs.writeFileSync(path.join(OUT, 'emoji-data.js'),
    "'use strict';\n// Generated by tools/vendor.js from unicode-emoji-json and emojilib (MIT). Do not edit.\n" +
    'const EMOJI_DATA = ' + JSON.stringify(data) + ';\n');
} catch (err) {
  console.warn('vendor: emoji data not built:', err.message);
  missing++;
}
console.log(missing ? `vendor: done with ${missing} missing file(s)` : 'vendor: libraries copied to vendor/');
