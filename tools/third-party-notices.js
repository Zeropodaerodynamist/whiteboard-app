'use strict';
// Writes THIRD-PARTY-NOTICES.md: the licences of everything shipped with the app.
//   - the JavaScript libraries copied into vendor/ (and the emoji data built from two packages)
//   - every Rust crate compiled into the native helpers (see PACKAGES below)
// Crates offered under several licences ("MIT OR Apache-2.0") are used under Apache-2.0,
// whose full text is in LICENSE; their own NOTICE files, if any, are reproduced. Crates with
// any other licence get their licence files reproduced in full.
// Usage: node tools/third-party-notices.js   (needs npm install and Rust)

const { execFileSync } = require('child_process');
const fs = require('fs');
const path = require('path');

const ROOT = path.join(__dirname, '..');
const NATIVE = path.join(ROOT, 'native');
// WB_NODE_MODULES: tools/export-public.js runs this in the public tree, which has no node_modules.
const NM = process.env.WB_NODE_MODULES || path.join(ROOT, 'node_modules');
// Our own crates, and the ones whose dependencies ship: [package, target, what it is].
const PACKAGES = [['swbd-ink', 'all', 'the handwriting recognition helper (`swbd-ink.exe`)']];
const OWN = new Set(['swbd-ink']);

const cargo = args => execFileSync('cargo', args, { cwd: NATIVE, encoding: 'utf8', maxBuffer: 64 * 1024 * 1024 });

// Crates that end up in the shipped binaries: normal (not dev or build) dependencies, on any platform.
const shipped = new Set();
for (const [pkg, target] of PACKAGES) {
  for (const line of cargo(['tree', '-p', pkg, '--target', target, '-e', 'normal', '--prefix', 'none', '--format', '{p}']).split('\n')) {
    const m = /^(\S+) v(\S+)/.exec(line.trim());
    if (m && !OWN.has(m[1])) shipped.add(`${m[1]} ${m[2]}`);
  }
}

const meta = JSON.parse(cargo(['metadata', '--format-version', '1', '--locked']));
const crates = meta.packages
  .filter(p => shipped.has(`${p.name} ${p.version}`))
  .sort((a, b) => a.name.localeCompare(b.name) || a.version.localeCompare(b.version));

const read = f => fs.readFileSync(f, 'utf8').replace(/\r\n/g, '\n').trim();
const filesIn = (dir, re) => (fs.existsSync(dir) ? fs.readdirSync(dir).filter(f => re.test(f)).sort().map(f => path.join(dir, f)) : []);
const fence = text => '```text\n' + text.replace(/```/g, "'''") + '\n```';
// "MIT OR Apache-2.0" and friends: we can take Apache-2.0.
const apacheChoice = lic => /\bApache-2\.0\b/.test(lic || '') && /\bOR\b|\//.test(lic || '');

const out = [];
out.push('# Third-party notices', '',
  'ZP Whiteboard is licensed under the Apache License 2.0 (see `LICENSE`). It ships with the third-party software below. This file is generated by `node tools/third-party-notices.js`; don\'t edit it by hand.', '',
  'The Electron runtime (MIT) and Chromium carry their own notices: `LICENSE.electron.txt` and `LICENSES.chromium.html` next to the app\'s executable.', '');

// ---------- JavaScript ----------
const JS = [
  ['codemirror', 'vendor/codemirror/'],
  ['marked', 'vendor/marked.js'],
  ['dompurify', 'vendor/purify.min.js'],
  ['unicode-emoji-json', 'vendor/emoji-data.js (emoji names and groups)'],
  ['emojilib', 'vendor/emoji-data.js (emoji search keywords)'],
];
out.push('## JavaScript libraries', '');
for (const [name, where] of JS) {
  const dir = path.join(NM, name);
  const pkg = JSON.parse(fs.readFileSync(path.join(dir, 'package.json'), 'utf8'));
  const lic = typeof pkg.license === 'string' ? pkg.license : (pkg.license && pkg.license.type) || 'see below';
  out.push(`### ${name} ${pkg.version}`, '', `Used in: ${where}. Licence: ${lic}.`, '');
  const files = filesIn(dir, /^(LICEN[CS]E|COPYING|NOTICE)/i);
  if (!files.length) throw new Error(`no licence file in node_modules/${name}`);
  for (const f of files) out.push(fence(read(f)), '');
}

// ---------- Rust ----------
const apache = crates.filter(c => apacheChoice(c.license) || c.license === 'Apache-2.0');
const other = crates.filter(c => !apache.includes(c));
out.push('## Rust crates', '',
  `${crates.length} crates are compiled into ${new Intl.ListFormat('en', { type: 'conjunction' }).format(PACKAGES.map(p => p[2]))}.`, '',
  '### Used under the Apache License 2.0', '',
  'The full licence text is in `LICENSE`. Where a crate offers a choice of licences, ZP Whiteboard uses it under Apache-2.0.', '',
  '| Crate | Version | Licence offered |', '|---|---|---|',
  ...apache.map(c => `| ${c.name} | ${c.version} | ${c.license} |`), '');
for (const c of apache) {
  for (const f of filesIn(path.dirname(c.manifest_path), /^NOTICE/i)) out.push(`#### NOTICE from ${c.name} ${c.version}`, '', fence(read(f)), '');
}
out.push('### Under other licences', '');
for (const c of other) {
  out.push(`#### ${c.name} ${c.version}`, '', `Licence: ${c.license || c.license_file || 'unknown'}.`, '');
  const files = filesIn(path.dirname(c.manifest_path), /^(LICEN[CS]E|COPYING|NOTICE|UNLICENSE)/i);
  if (!files.length) throw new Error(`no licence file in crate ${c.name} ${c.version}`);
  for (const f of files) out.push(fence(read(f)), '');
}

fs.writeFileSync(path.join(ROOT, 'THIRD-PARTY-NOTICES.md'), out.join('\n'));
console.log(`THIRD-PARTY-NOTICES.md: ${JS.length} JavaScript libraries, ${crates.length} crates (${apache.length} under Apache-2.0, ${other.length} other)`);
